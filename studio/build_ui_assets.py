"""Index and validate UI artwork without altering any generated image pixels."""
from pathlib import Path
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "assets" / "ui-v1"
SOURCE = ROOT / "src" / "ui"
SOURCE.mkdir(exist_ok=True)
ATLAS_ID = "rbxassetid://98237999999525"
ROWS = [
    ["pepper_seeds", "carrot_seeds", "lettuce_seeds", "pumpkin_seeds"],
    ["grape_seeds", "corn_seeds", "wheat_seeds", "potato_seeds"],
    ["pepper_harvest", "carrot_harvest", "lettuce_harvest", "pumpkin_harvest"],
    ["grape_harvest", "corn_harvest", "wheat_harvest", "potato_harvest"],
    ["shovel", "watering_can", "fertilizer_bag", "bag"],
    ["sterne", "chest_closed", "chest_open", "hand"],
]
LABELS = {"watering_can": "Watering Can", "fertilizer_bag": "Fertilizer", "chest_closed": "Chest", "chest_open": "Chest"}
im = Image.open(OUT / "items-atlas.png")
assert im.mode == "RGBA" and im.size == (1024, 1536), (im.mode, im.size)
alpha = im.getchannel("A")
mask = alpha.point(lambda v: 255 if v >= 16 else 0)
hist = alpha.histogram()
assert hist[0] > im.width * im.height * .4
sprites = {}
checks = []
for row, names in enumerate(ROWS):
    for col, name in enumerate(names):
        # The can's spout crosses its nominal grid cell. Explicit sampling regions
        # preserve it intact; the neighboring sack starts farther right.
        left, top, right, bottom = col*256, row*256, (col+1)*256, (row+1)*256
        if name == "watering_can": right = 532
        if name == "fertilizer_bag": left = 532
        box = mask.crop((left, top, right, bottom)).getbbox()
        assert box is not None, name
        x0, y0, x1, y1 = box
        rect = [max(left, left+x0-3), max(top, top+y0-3), min(right, left+x1+3), min(bottom, top+y1+3)]
        x, y, r, b = rect
        assert r-x > 100 and b-y > 100, (name, rect)
        assert 0 <= x < r <= im.width and 0 <= y < b <= im.height
        # Check every sample-region boundary for alpha that could be clipped.
        edge = max(mask.crop((left, top, right, top+1)).getextrema()[1],
                   mask.crop((left, bottom-1, right, bottom)).getextrema()[1],
                   mask.crop((left, top, left+1, bottom)).getextrema()[1],
                   mask.crop((right-1, top, right, bottom)).getextrema()[1])
        assert edge == 0, (name, "artwork crosses sampling region")
        kind = "Seed" if name.endswith("_seeds") else "Produce" if name.endswith("_harvest") else "Utility"
        label = LABELS.get(name, name.split("_")[0].title())
        sprites[name] = {"label": label, "kind": kind, "rect": [x,y,r-x,b-y], "row": row, "column": col}
        checks.append({"id":name,"regionClear":True,"rect":[x,y,r-x,b-y]})

theme = {
    "cream":"#FFF5D6", "creamRaised":"#FFF9E8", "slot":"#F6E9C5",
    "ink":"#17371E", "green":"#285B2D", "outline":"#DBC798", "muted":"#577052",
    "blue":"#417CAD", "silver":"#B7C3CA", "gold":"#DEAD43",
    "panelRadius":24, "buttonRadius":18, "itemRadius":16, "toolSize":80,
    "itemSize":104, "labelSize":26, "numberSize":30, "titleSize":34,
    "font":"GothamBold", "hoverSeconds":.10, "pressSeconds":.08,
}
manifest = {
    "version":1,"source":"items-atlas.png","image":ATLAS_ID,
    "dimensions":list(im.size),"runtimeDimensions":[682,1023],"sha256":hashlib.sha256((OUT/"items-atlas.png").read_bytes()).hexdigest(),
    "sprites":sprites,"theme":theme,
    "controls":"UIPrimitives.luau; drawn in code, never baked into the item art",
    "status":"Uploaded artwork; integration with the farming runtime remains a separate step.",
}
(OUT/"manifest.json").write_text(json.dumps(manifest,indent=2)+"\n",encoding="utf-8")

lines = ["-- Generated by studio/build_ui_assets.py. Pixel rectangles refer to the uploaded source texture.",
         "local A = {}",f'A.Image = "{ATLAS_ID}"',"A.SourceSize = Vector2.new(1024,1536)","A.TextureSize = Vector2.new(682,1023) -- Verified served dimensions in Studio", "A.Sprites = {"]
for key,s in sprites.items():
    x,y,w,h=s["rect"]
    lines.append(f'    {key} = {{Offset=Vector2.new({x},{y}), Size=Vector2.new({w},{h}), Label="{s["label"]}"}},')
lines.extend(["}","A.Colors = {"])
for key,value in theme.items():
    if isinstance(value,str) and value.startswith("#"):
        rgb=[int(value[i:i+2],16) for i in (1,3,5)]
        lines.append(f'    {key}=Color3.fromRGB({rgb[0]},{rgb[1]},{rgb[2]}),')
lines.extend(["}","function A.apply(image, id)","    local sprite = assert(A.Sprites[id], \"Unknown UI icon: \"..tostring(id))",
              "    image.Image=A.Image", "    local ratio=A.TextureSize/A.SourceSize", "    local start=sprite.Offset*ratio", "    local finish=(sprite.Offset+sprite.Size)*ratio", "    local offset=Vector2.new(math.floor(start.X),math.floor(start.Y))", "    image.ImageRectOffset=offset", "    image.ImageRectSize=Vector2.new(math.ceil(finish.X),math.ceil(finish.Y))-offset",
              "    image.ScaleType=Enum.ScaleType.Fit", "    image.BackgroundTransparency=1", "    return image", "end", "return A", ""])
(SOURCE/"UIAssets.luau").write_text("\n".join(lines),encoding="utf-8")
report={"textureMode":im.mode,"dimensions":list(im.size),"transparentFraction":hist[0]/(im.width*im.height),
        "spriteCount":len(sprites),"checks":checks,"image":ATLAS_ID,"sha256":manifest["sha256"]}
(OUT/"asset-verification.json").write_text(json.dumps(report,indent=2)+"\n",encoding="utf-8")
print(json.dumps({"sprites":len(sprites),"transparentFraction":report["transparentFraction"],"image":ATLAS_ID}))
